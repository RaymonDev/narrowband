//side experiment: fold levels above 9 into 9
{
  const manifest = JSON.parse(readFileSync(join(root, 'corpus/manifest.json'), 'utf8')) as { type: string; file: string }[]
  const frameBytes = (levels: Uint8Array) =>
    QUADRANTS.reduce((n, r) => n + compressedSize(packGray4(crop({ width: 576, height: 288, levels }, r.x, r.y, r.width, r.height))), 0)
  const byType = new Map<string, { share: number[]; saving: number[] }>()
  for (const e of manifest) {
    const img = decodePng(new Uint8Array(readFileSync(join(root, 'corpus', e.file))))
    const q = quantize({ width: img.width, height: img.height, data: img.data }, { method: 'none', levels: 16 })
    const folded = q.levels.map((l) => Math.min(l, 9))
    const a = byType.get(e.type) ?? { share: [], saving: [] }
    a.share.push(q.levels.filter((l) => l > 9).length / q.levels.length)
    a.saving.push(1 - frameBytes(folded) / frameBytes(q.levels))
    byType.set(e.type, a)
  }
  md.push('## Side experiment: folding levels 10–15 into 9')
  md.push('')
  md.push('The simulator draws levels 9–15 identically (Phase 0), and g2-kit reports by eye that G2 brightness levels off around 8–10. If the panel truly saturates, levels above 9 can be sent as 9 at no visible cost. Same baseline, levels > 9 replaced by 9:')
  md.push('')
  table(
    ['content', 'pixels above level 9', 'bytes saved'],
    [...byType].map(([t, a]) => [t, pct(mean(a.share), 1), pct(mean(a.saving), 1)]),
  )
}

